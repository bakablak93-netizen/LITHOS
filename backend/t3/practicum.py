def compute_two_probes_state(
    rho_f: float = 1.20,
    rho_v: float = 0.05,
    vnk_depth_m: float = 2425.0,
) -> dict[str, Any]:
    """
    Вычисляет единое состояние модели для практикума «Что показывают два зонда?»
    на интервале 2408–2442 м (плотный прослой 2409–2416 м, продуктивный коллектор 2416–2433 м с ВНК = 2425 м,
    глинистая перемычка 2433–2441 м).
    """
    sim = simulate_well_log(
        depth_start_m=2408.0,
        depth_end_m=2442.0,
        step_m=1.0,
        rho_v=rho_v,
        rho_f=rho_f,
        vnk_depth_m=vnk_depth_m,
    )
    logs = sim["logs"]
    depths = logs["depth_m"]

    # Характерные опорные глубины для разреза и сравнения состояний:
    # 2412 м — плотный неколлектор; 2420 м — нефтяная часть коллектора (выше ВНК); 2429 м — водоносная часть (ниже ВНК)
    def _at_depth(target_z: float) -> dict[str, Any]:
        idx = min(range(len(depths)), key=lambda i: abs(depths[i] - target_z))
        bk = logs["rho_bk_ohmm"][idx]
        mbk = logs["rho_mbk_ohmm"][idx]
        return {
            "depth_m": depths[idx],
            "k_p_pct": logs["k_p_pct"][idx],
            "alpha_sp": logs["alpha_sp"][idx],
            "sp_mv": logs["sp_mv"][idx],
            "p_p": logs["p_p"][idx],
            "rho_vp_ohmm": logs["rho_vp_ohmm"][idx],
            "rho_bk_ohmm": bk,
            "rho_mbk_ohmm": mbk,
            "p_n": logs["p_n"][idx],
            "k_v": logs["k_v"][idx],
            "k_ng": logs["k_ng"][idx],
            "is_reservoir": logs["is_reservoir"][idx],
            "saturation_class": logs["saturation_class"][idx],
            "invasion_profile": "понижающее (ρ_МБК < ρ_БК)" if mbk < bk * 0.92 else "повышающее (ρ_МБК > ρ_БК)" if mbk > bk * 1.08 else "близко к равному (ρ_МБК ≈ ρ_БК)",
        }

    tight_pt = _at_depth(2412.0)
    oil_pt = _at_depth(2420.0)
    water_pt = _at_depth(2429.0)

    return {
        "data_origin": "Симуляция (детерминированная модель backend.physics_engine.latyshova_gis.simulate_well_log)",
        "parameters": {
            "rho_f_ohmm": round(rho_f, 2),
            "rho_v_ohmm": round(rho_v, 3),
            "vnk_depth_m": vnk_depth_m,
            "delta_e_max_mv": sim["parameters"]["delta_e_max_mv"],
            "m": sim["parameters"]["m"],
            "n": sim["parameters"]["n"],
        },
        "summary": sim["summary"],
        "key_zones": {
            "tight_layer_2412m": tight_pt,
            "oil_zone_2420m": oil_pt,
            "water_zone_2429m": water_pt,
        },
        "curves": {
            "depth_m": depths,
            "rho_bk_ohmm": logs["rho_bk_ohmm"],
            "rho_mbk_ohmm": logs["rho_mbk_ohmm"],
            "alpha_sp": logs["alpha_sp"],
            "k_p_pct": logs["k_p_pct"],
            "saturation_class": logs["saturation_class"],
        },
    }


