def _validate_step_title_words(title: str) -> str:
    """Гарантирует, что самостоятельный заголовок шага содержит от 3 до 7 слов."""
    words = [w for w in title.strip().split() if w]
    if 3 <= len(words) <= 7:
        return " ".join(words)
    if len(words) < 3:
        padded = words + ["в", "модели", "пласта"]
        return " ".join(padded[:5])
    return " ".join(words[:7])


